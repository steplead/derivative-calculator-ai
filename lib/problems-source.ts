/**
 * problems-source.ts — authoritative server-side problem source.
 *
 * WHY THIS MODULE EXISTS (RC-8)
 * ----------------------------
 * Every page used to load /problems.json with:
 *
 *     fetch(url, { cache: 'force-cache', next: { revalidate: 3600 } })
 *
 * In this deployment (Next.js 14 App Router on Cloudflare Pages via
 * @cloudflare/next-on-pages) that fetch NEVER yields data:
 *   - Next.js only wires `globalThis.__incrementalCache` when the platform
 *     adapter supplies an `IncrementalCache` implementation
 *     (node_modules/next/dist/server/web/adapter.js: "if (!globalThis.__incrementalCache
 *      && params.IncrementalCache)").
 *   - next-on-pages does not supply one, so the force-cache/revalidate code
 *     path has no cache handler to read from.
 *   - Observed production effect: /problems and /problems/[type] render with
 *     ZERO problems, and every /[slug] page silently fell through to the
 *     `parseSlugToMath()` heuristic, publishing slug-derived formulas
 *     (e.g. "1-x" -> "1x") instead of the authoritative "1/x" from the library.
 *
 * The plain `fetch(url)` used by /directory (and by generateMetadata's
 * fallback) works in production. This module standardises on that proven path,
 * and memoises the parsed array per isolate so the 900 KB payload is fetched
 * and parsed once instead of on every request.
 *
 * RULES
 *   1. Plain fetch only — never `cache: 'force-cache'` / `next: { revalidate }`.
 *   2. Read the response body exactly once (reading twice throws
 *      "body used already").
 *   3. Never throw into the caller's critical path unless the caller opts in.
 */

import { getBaseUrl } from '@/utils/robust-url';
import { displayExpression } from '@/lib/math/math-core';

export type StaticProblem = {
    slug: string;
    formula: string;
    title?: string;
    description?: string;
    type?: 'derivative' | 'integral' | 'limit';
    limitTo?: string;
    difficulty?: string;
    // B4: tags is a comma-separated string (e.g. "derivative,polynomial"),
    // matching the on-disk shape in /problems.json. Kept as string — not a
    // parsed array — to stay compatible with the existing data model and the
    // /api/problems consumer; split on demand at the call site.
    tags?: string;
};

/** Parsed library, memoised per isolate. */
let memoryCache: StaticProblem[] | null = null;
/** Deduplicates concurrent first-hits in the same isolate. */
let inflight: Promise<StaticProblem[]> | null = null;

/**
 * Load the full problem library.
 * Returns [] (never throws) when the source is unreachable so callers can
 * degrade to their own fallbacks instead of rendering a 500.
 */
export async function loadStaticProblems(): Promise<StaticProblem[]> {
    if (memoryCache) return memoryCache;
    if (inflight) return inflight;

    const base = getBaseUrl();

    inflight = (async (): Promise<StaticProblem[]> => {
        const res = await fetch(`${base}/problems.json`);
        if (!res.ok) {
            throw new Error(`/problems.json responded HTTP ${res.status}`);
        }
        const data: unknown = await res.json();
        if (!Array.isArray(data)) {
            throw new Error('/problems.json did not return an array');
        }
        memoryCache = data as StaticProblem[];
        return memoryCache;
    })();

    try {
        return await inflight;
    } finally {
        inflight = null;
    }
}

/**
 * Safe variant used inside page render paths: any failure degrades to [].
 */
export async function loadStaticProblemsSafe(): Promise<StaticProblem[]> {
    try {
        return await loadStaticProblems();
    } catch {
        return [];
    }
}

/** Exact slug lookup against the loaded library. */
export function findStaticProblem(
    rows: StaticProblem[],
    slug: string
): StaticProblem | null {
    if (!Array.isArray(rows) || !slug) return null;
    return rows.find((p) => p && p.slug === slug) || null;
}

/** Test-only: drop the memoised library. */
export function resetStaticProblemsCache(): void {
    memoryCache = null;
    inflight = null;
}

/**
 * Split the library by problem type.
 *
 * Shared by /problems, /problems/[type] and the regression tests so the tests
 * exercise the real filter instead of a copy of it. Library rows created before
 * the `type` column existed carry no type; they are all derivatives.
 */
export function filterByType(
    problems: StaticProblem[],
    type: string
): StaticProblem[] {
    if (!Array.isArray(problems)) return [];
    if (type === 'derivative') {
        return problems.filter((p) => p && (!p.type || p.type === 'derivative'));
    }
    return problems.filter((p) => p && p.type === type);
}

/**
 * Slugs containing either token are machine-generated by the slug-math
 * fallback (e.g. derivative-of-1-minus-over-minus-sqrt1-minus-x-minus-to-minus-the-minus-2
 * or derivative-of-10-minus-over-minus-x). They are near-duplicates with
 * unreadable URLs: noindexed, absent from the sitemap, and not worth a crawl
 * link. getDerivativeCanonicalMap uses the same artifact to reject them when
 * choosing a group's primary slug.
 *
 * Verified against the 3,137-slug library: these two tokens match 780 slugs
 * and ZERO of the 50 sitemap allowlist slugs, so filtering cannot drop an
 * indexable, impression-bearing page.
 */
const MACHINE_SLUG_TOKENS = [
    'minus-to-minus-the-minus',
    '-minus-over-minus-',
];

export function isMachineSlug(slug: string): boolean {
    return MACHINE_SLUG_TOKENS.some((token) => slug.includes(token));
}

/**
 * Practice-window quality gate (2026-11-07 review): a related link is only worth
 * showing if it has a real, non-trivial derivative. Drop:
 *   - non-differentiable functions (floor/ceil/round/sign) — the engine returns an
 *     unevaluated diff echo and validateDerivativeResult flags them invalid, so
 *     publishing them as "Derivative of floor(x)" teaches nothing and risks a
 *     wrong-looking answer block;
 *   - pure constants (no variable x) — d/dx of a constant is 0, trivial filler.
 * The site is exclusively d/dx of x, so a formula without x is always constant.
 */
const NONDIFF_TOKENS = ['floor(', 'ceil(', 'round(', 'sign('];

function isWorthyPractice(p: StaticProblem): boolean {
    const f = (p.formula || '').toLowerCase();
    if (!f) return false;
    if (NONDIFF_TOKENS.some((t) => f.includes(t))) return false;
    if (!/x/.test(f)) return false; // pure constant → derivative 0, trivial
    return true;
}

/**
 * RC-6 FIX: stable, deterministic related-problem selection.
 * - Excludes the current slug.
 * - Excludes machine-generated near-duplicate slugs (2026-11-06 GSC review).
 * - Prefers problems of the same type (derivative/integral/limit).
 * - When `featuredOnly` (the sitemap allowlist) is supplied, the candidate pool
 *   is restricted to those indexable slugs so high-value pages never spend link
 *   equity on noindex'd machine pages (derivative-of-10cosx, derivative-of-1-x,
 *   ...) — 2026-11-06 third review. The allowlist does not contain the
 *   `derivative-of-1-x` / `derivative-of-1-over-x` duplicate pair, so the
 *   redundant "Derivative of 1/x" entry is dropped automatically.
 * - RULE-FAMILY SAMPLING + PER-PAGE ROTATION (2026-11 review): instead of always
 *   showing the lexicographic top-`limit` (so the same 10 pages linked from
 *   every page), we rank the pool by the current page's OWN rule family
 *   (exponential / trig / log / quotient / ... first), then rotate the window by
 *   a deterministic hash of `currentSlug`. Every featured page therefore surfaces
 *   a DIFFERENT set of links, spreading equity across the whole allowlist and
 *   giving each page real internal links (previously ~40 of 50 got zero).
 * - Deterministic (no Math.random). Caps at `limit`. Fail-open: if the allowlist
 *   somehow matches nothing, the unfiltered pool is used so the block never
 *   silently empties. Never returns duplicates.
 */

/** Deterministic 32-bit FNV-1a hash → non-negative int (no Math.random). */
function slugHash(s: string): number {
    let h = 2166136261;
    for (let i = 0; i < s.length; i++) {
        h ^= s.charCodeAt(i);
        h = Math.imul(h, 16777619);
    }
    return h >>> 0;
}

/** Coarse rule-family label derived from a formula, used to group related links. */
function classifyFamily(formula: string | undefined): string {
    const f = (formula || '').toLowerCase();
    if (/\^x\b|\bexp\(|e\^\(|to-the-x|to-the-power|e-to-the|a-to-the/.test(f)) return 'exponential';
    if (/\b(sin|cos|tan|sec|csc|cot|arcsin|arccos|arctan)/.test(f)) return 'trig';
    if (/ln\(|log\(/.test(f)) return 'log';
    if (/\//.test(f)) return 'quotient';
    if (/\*/.test(f)) return 'product';
    if (/\^/.test(f)) return 'power';
    return 'basic';
}

export function pickStableRelated(
    problems: StaticProblem[],
    currentSlug: string,
    typeHint?: string,
    limit: number = 10,
    featuredOnly?: Set<string> | null
): StaticProblem[] {
    if (!Array.isArray(problems) || problems.length === 0) return [];
    const type = typeHint || 'derivative';
    let pool = problems.filter(
        (p) => p && p.slug && p.slug !== currentSlug && !isMachineSlug(p.slug) && isWorthyPractice(p)
    );
    if (featuredOnly && featuredOnly.size > 0) {
        const before = pool.length;
        pool = pool.filter((p) => featuredOnly.has(p.slug));
        // Fail-open: never hide every related link on a data regression.
        if (pool.length === 0 && before > 0) {
            pool = problems.filter(
                (p) => p && p.slug && p.slug !== currentSlug && !isMachineSlug(p.slug) && isWorthyPractice(p)
            );
        }
    }
    // Same-type preference: derivative pages link to derivative pages first.
    const sameType = pool.filter((p) => (!p.type || p.type === type));
    const finalPool = sameType.length >= limit
        ? sameType
        : [...sameType, ...pool.filter((p) => p.type && p.type !== type)];
    if (finalPool.length === 0) return [];

    // Rank by the current page's own rule family (its family first), then slug.
    const currentFormula = (problems.find((p) => p.slug === currentSlug)?.formula) || currentSlug;
    const fam = classifyFamily(currentFormula);
    const ranked = [...finalPool].sort((a, b) => {
        const af = classifyFamily(a.formula) === fam ? 0 : 1;
        const bf = classifyFamily(b.formula) === fam ? 0 : 1;
        if (af !== bf) return af - bf;
        return (a.slug || '').localeCompare(b.slug || '');
    });

    // Rotate the window by a deterministic hash of the current slug so every
    // featured page surfaces a different slice of the allowlist.
    const offset = slugHash(currentSlug) % ranked.length;
    const rotated = ranked.slice(offset).concat(ranked.slice(0, offset));
    const windowed = rotated.slice(0, limit);

    // Dedup by DISPLAYED formula so two slugs that collapse to the same visible
    // name never appear twice in the same window. We only drop a later entry when
    // its display matches an earlier one AND its RAW formula differs — i.e. a true
    // alias collision such as `log(x)` and `ln(x)` both rendering "Derivative of
    // ln(x)", or `exp(2*x)` vs `e^(2x)`. Two genuinely distinct slugs that happen
    // to share a display (identical raw formula) are kept, so internal-link
    // coverage is not silently collapsed.
    const seenFormula = new Map<string, string>(); // displayKey -> first raw formula (lowercased)
    const deduped: StaticProblem[] = [];
    for (const p of windowed) {
        const key = displayExpression(p.formula || '').toLowerCase();
        const raw = (p.formula || '').toLowerCase();
        const first = seenFormula.get(key);
        if (first !== undefined && first !== raw) continue; // alias collision → drop duplicate
        seenFormula.set(key, raw);
        deduped.push(p);
    }
    return deduped;
}

/**
 * P2-G: deterministic canonical map for derivative near-duplicates.
 *
 * Two derivative problems that share a `formula` render an identical <title>
 * ("Derivative of <formula>") and identical math (d/dx is unique per formula),
 * so they are TRUE near-duplicates. We pick one primary slug per formula group
 * and return a map { nonPrimarySlug -> primarySlug } so those pages can emit
 * <link rel="canonical" href={primary}> and consolidate indexing equity.
 *
 * SCOPE IS DELIBERATELY DERIVATIVES ONLY:
 *   - Limit problems with the same formula but different limit points (x->0 vs
 *     x->infinity) are genuinely different content -> stay self-canonical.
 *   - Integral problems with the same formula but different bounds (0..1 vs
 *     1..3) are genuinely different content -> stay self-canonical.
 * Canonicalising those would wrongly merge distinct problems, so they are
 * excluded by the `type === 'derivative'` guard below.
 *
 * Primary selection (deterministic, no guessing):
 *   1. Prefer "clean" slugs: start with `derivative-of-` and NOT contain the
 *      slug-math auto-fallback artifact `minus-to-minus-the-minus`.
 *   2. Among the clean pool, pick the lexicographically smallest slug.
 *   3. If a group has no clean slug, fall back to the lexicographically
 *      smallest overall (still deterministic).
 *
 * Memoised per isolate; returns {} (never throws) so a source failure simply
 * leaves every page self-canonical (fail-closed, no broken canonical links).
 */
let _derivCanonicalCache: Map<string, string> | null = null;

export async function getDerivativeCanonicalMap(
    problems?: StaticProblem[]
): Promise<Map<string, string>> {
    // When called without a library (production path) the result is memoised
    // per isolate. When given an explicit library (tests), we rebuild fresh and
    // do NOT touch the cache.
    if (!problems && _derivCanonicalCache) return _derivCanonicalCache;
    const map = new Map<string, string>();
    const lib = problems ?? (await loadStaticProblemsSafe());
    const byFormula = new Map<string, string[]>();
    for (const p of lib) {
        if (!p || (p.type || 'derivative') !== 'derivative') continue;
        const f = p.formula || '';
        if (!f) continue;
        if (!byFormula.has(f)) byFormula.set(f, []);
        byFormula.get(f)!.push(p.slug);
    }
    for (const slugs of byFormula.values()) {
        if (slugs.length < 2) continue;
        const clean = slugs.filter(
            (s) => s.startsWith('derivative-of-') && !s.includes('minus-to-minus-the-minus')
        );
        const pool = clean.length ? clean : slugs;
        const primary = [...pool].sort()[0];
        for (const s of slugs) {
            if (s !== primary) map.set(s, primary);
        }
    }
    if (!problems) _derivCanonicalCache = map;
    return map;
}
